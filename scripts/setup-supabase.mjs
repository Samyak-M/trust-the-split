#!/usr/bin/env node
/**
 * One-command Supabase setup for StallSplit.
 *
 * Usage:
 *   set SUPABASE_ACCESS_TOKEN=sbp_...   (Windows)
 *   npm run setup:supabase
 *
 * Get a token: https://supabase.com/dashboard/account/tokens
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const PROJECT_REF = "hrfeksphjblkigrixtjl";
const API = "https://api.supabase.com/v1";
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const REDIRECT_URLS = [
  "http://localhost:8000",
  "http://localhost:8000/",
  "http://127.0.0.1:8000",
  "http://127.0.0.1:8000/",
  "https://samyak-m.github.io/trust-the-split",
  "https://samyak-m.github.io/trust-the-split/"
];

const token = process.env.SUPABASE_ACCESS_TOKEN?.trim();
if (!token) {
  console.error(`
Missing SUPABASE_ACCESS_TOKEN.

1. Open https://supabase.com/dashboard/account/tokens
2. Create a token (name: StallSplit setup)
3. Run:

   Windows PowerShell:
   $env:SUPABASE_ACCESS_TOKEN="sbp_..."
   npm run setup:supabase
`);
  process.exit(1);
}

async function api(method, path, body) {
  const res = await fetch(`${API}${path}`, {
    method,
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json"
    },
    body: body ? JSON.stringify(body) : undefined
  });
  const text = await res.text();
  let data;
  try { data = text ? JSON.parse(text) : null; } catch { data = text; }
  if (!res.ok) {
    const msg = typeof data === "object" ? (data.message || data.error || JSON.stringify(data)) : data;
    throw new Error(`${method} ${path} → ${res.status}: ${msg}`);
  }
  return data;
}

function pickAnonKey(keys) {
  const legacy = keys.find(k => k.name === "anon" || k.type === "legacy" && k.name?.includes("anon"));
  if (legacy?.api_key) return legacy.api_key;
  const publishable = keys.find(k => k.type === "publishable" || k.name === "default" && k.type === "publishable");
  if (publishable?.api_key) return publishable.api_key;
  const any = keys.find(k => k.api_key && (k.type === "legacy" || k.type === "publishable"));
  return any?.api_key || "";
}

async function runSchema() {
  const sql = readFileSync(join(ROOT, "supabase", "schema.sql"), "utf8");
  // Management API runs one statement at a time for some commands; split on semicolons carefully
  const statements = sql
    .split(/;\s*\n/)
    .map(s => s.replace(/^--[^\n]*\n?/gm, "").trim())
    .filter(s => s.length > 0);

  console.log(`Running ${statements.length} SQL statements…`);
  for (let i = 0; i < statements.length; i++) {
    const stmt = statements[i];
    if (!stmt) continue;
    try {
      await api("POST", `/projects/${PROJECT_REF}/database/query`, { query: stmt + ";" });
      process.stdout.write(".");
    } catch (e) {
      // Some statements may fail on re-run (policies already exist) — continue
      if (/already exists|duplicate/i.test(e.message)) {
        process.stdout.write("s");
      } else {
        console.error(`\nStatement ${i + 1} failed:`, e.message);
        console.error(stmt.slice(0, 120) + "…");
      }
    }
  }
  console.log(" done");
}

async function configureAuth() {
  console.log("Configuring auth redirect URLs…");
  let current = {};
  try {
    current = await api("GET", `/projects/${PROJECT_REF}/config/auth`);
  } catch { /* use defaults */ }

  const existing = String(current.uri_allow_list || "")
    .split(",")
    .map(s => s.trim())
    .filter(Boolean);
  const merged = [...new Set([...existing, ...REDIRECT_URLS])];

  await api("PATCH", `/projects/${PROJECT_REF}/config/auth`, {
    site_url: current.site_url || REDIRECT_URLS[0],
    uri_allow_list: merged.join(","),
    external_email_enabled: true
  });
  console.log("  Redirect URLs:", merged.join(", "));
}

async function writeConfig(anonKey) {
  const url = `https://${PROJECT_REF}.supabase.co`;
  const content = `/**
 * Auto-generated by scripts/setup-supabase.mjs
 * Project Settings → API → Project URL and anon public key.
 */
export const SUPABASE = {
  url: "${url}",
  anonKey: "${anonKey}"
};
`;
  writeFileSync(join(ROOT, "src", "config.js"), content, "utf8");
  console.log("Wrote src/config.js");
}

async function verifyConnection(anonKey) {
  const url = `https://${PROJECT_REF}.supabase.co/rest/v1/`;
  const res = await fetch(url, {
    headers: { apikey: anonKey, Authorization: `Bearer ${anonKey}` }
  });
  if (!res.ok && res.status !== 404) {
    console.warn("  Warning: REST API check returned", res.status);
  } else {
    console.log("  API connection verified");
  }
}

async function main() {
  console.log(`Setting up Supabase project: ${PROJECT_REF}\n`);

  console.log("Fetching API keys…");
  const keys = await api("GET", `/projects/${PROJECT_REF}/api-keys?reveal=true`);
  const anonKey = pickAnonKey(keys);
  if (!anonKey) throw new Error("Could not find anon/publishable key in API response.");

  await runSchema();
  await configureAuth();
  await writeConfig(anonKey);
  await verifyConnection(anonKey);

  console.log(`
✓ Setup complete!

Next steps:
  1. npm run dev
  2. Open http://localhost:8000 → Share → enter your email
  3. Click the sign-in link in your email

Your app is configured for cloud sync.`);
}

main().catch(e => {
  console.error("\nSetup failed:", e.message);
  process.exit(1);
});
